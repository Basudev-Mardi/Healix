"use client";

import React, { useMemo, useState } from "react";
import type { LabReport, LabRequest, LabResult } from "@/lib/lab/types";
import {
  ACCENT_BTN_CLASS,
  PRIMARY_BTN_CLASS,
  formatDateTime,
  getLabBadgeClass,
} from "./ui";

interface DigitalReportsSectionProps {
  requests: LabRequest[];
  results: LabResult[];
  reports: LabReport[];
  preselectedRequestId?: string;
  canGenerate: boolean;
  onGenerateReport: (requestId: string) => Promise<boolean>;
}

function escapeHtml(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function printLabReportPdf(report: LabReport) {
  const snap = report.reportSnapshot;
  const rowsHtml = snap.results
    .map(
      (r) => `
      <tr>
        <td><strong>${escapeHtml(r.testCode)}</strong> — ${escapeHtml(r.testName)}</td>
        <td><strong>${escapeHtml(r.resultValue)}</strong> ${escapeHtml(r.unit)}</td>
        <td>${escapeHtml(r.referenceRange || "Qualitative")}</td>
        <td>${
          r.isOutOfRange
            ? '<span style="color:#c93b1d;font-weight:700;">Out of Range</span>'
            : '<span style="color:#2a7d6c;font-weight:600;">Normal</span>'
        }</td>
        <td>${escapeHtml(r.remarks || "—")}</td>
      </tr>`
    )
    .join("");

  const html = `<!doctype html>
<html>
<head>
  <meta charset="utf-8" />
  <title>Laboratory Report ${escapeHtml(report.id)}</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; color: #14191b; padding: 32px; max-width: 860px; margin: 0 auto; }
    .header { display: flex; justify-content: space-between; align-items: flex-start; border-bottom: 2px solid #181c1e; padding-bottom: 14px; margin-bottom: 20px; }
    .brand { font-size: 20px; font-weight: 700; letter-spacing: -0.02em; }
    .sub { font-size: 12px; color: #546369; margin-top: 2px; }
    .meta { display: grid; grid-template-columns: repeat(2, 1fr); gap: 10px 24px; background: #f4f7f8; border: 1px solid #dce4e7; border-radius: 12px; padding: 14px 16px; font-size: 12px; margin-bottom: 20px; }
    .meta strong { color: #14191b; }
    table { width: 100%; border-collapse: collapse; font-size: 12px; margin-bottom: 24px; }
    th, td { border-bottom: 1px solid #dce4e7; padding: 10px 8px; text-align: left; }
    th { background: #edf2f3; font-size: 11px; text-transform: uppercase; letter-spacing: 0.04em; color: #47565c; }
    .footer { display: flex; justify-content: space-between; border-top: 1px solid #dce4e7; padding-top: 14px; font-size: 11px; color: #546369; }
    @media print { body { padding: 12px; } }
  </style>
</head>
<body>
  <div class="header">
    <div>
      <div class="brand">Healix Hospital — Clinical Laboratory Report</div>
      <div class="sub">Accredited Laboratory Information System (LIS) • Digital Verified Report</div>
    </div>
    <div style="text-align:right;font-size:12px;">
      <div><strong>Report ID:</strong> ${escapeHtml(report.id)}</div>
      <div><strong>Generated:</strong> ${escapeHtml(formatDateTime(report.generatedAt))}</div>
    </div>
  </div>

  <div class="meta">
    <div><strong>Patient:</strong> ${escapeHtml(snap.patient.fullName)} (${escapeHtml(snap.patient.id)})</div>
    <div><strong>Referring Doctor:</strong> ${escapeHtml(snap.referringDoctor)}</div>
    <div><strong>Lab Request ID:</strong> ${escapeHtml(snap.requestId)}</div>
    <div><strong>Sample ID / Specimen:</strong> ${escapeHtml(snap.sampleId)} (${escapeHtml(snap.specimenType)})</div>
    <div><strong>Gender / DOB:</strong> ${escapeHtml(snap.patient.gender || "—")} / ${escapeHtml(snap.patient.dateOfBirth || "—")}</div>
    <div><strong>Priority:</strong> ${escapeHtml(snap.priority)}</div>
  </div>

  <table>
    <thead>
      <tr>
        <th>Test</th>
        <th>Result</th>
        <th>Reference Range</th>
        <th>Flag</th>
        <th>Remarks</th>
      </tr>
    </thead>
    <tbody>
      ${rowsHtml}
    </tbody>
  </table>

  <div class="footer">
    <div><strong>Verified By:</strong> ${escapeHtml(report.verifiedBy)}</div>
    <div><strong>Generated By:</strong> ${escapeHtml(report.generatedBy)}</div>
  </div>
</body>
</html>`;

  const win = window.open("", "_blank", "width=920,height=780");
  if (!win) return;
  win.document.open();
  win.document.write(html);
  win.document.close();
  win.focus();
  setTimeout(() => {
    win.print();
  }, 250);
}

export function DigitalReportsSection({
  requests,
  results,
  reports,
  preselectedRequestId,
  canGenerate,
  onGenerateReport,
}: DigitalReportsSectionProps) {
  const [selectedReportId, setSelectedReportId] = useState<string>("");
  const [busyReqId, setBusyReqId] = useState<string | null>(null);

  const reportByRequestId = useMemo(() => {
    const map = new Map<string, LabReport>();
    for (const rpt of reports) {
      map.set(rpt.requestId, rpt);
    }
    return map;
  }, [reports]);

  const requestReadiness = useMemo(() => {
    return requests
      .filter((req) => req.status !== "Cancelled")
      .map((req) => {
        const reqResults = results.filter((r) => r.requestId === req.id);
        const verifiedCount = reqResults.filter(
          (r) => r.verificationStatus === "Verified"
        ).length;
        const total = req.testIds.length;
        const isReady = total > 0 && verifiedCount >= total;
        const existingReport = reportByRequestId.get(req.id);
        return { req, verifiedCount, total, isReady, existingReport };
      });
  }, [requests, results, reportByRequestId]);

  const activeReport = useMemo(() => {
    if (selectedReportId) {
      const found = reports.find((r) => r.id === selectedReportId);
      if (found) return found;
    }
    if (preselectedRequestId) {
      const byReq = reports.find((r) => r.requestId === preselectedRequestId);
      if (byReq) return byReq;
    }
    return reports[0];
  }, [reports, selectedReportId, preselectedRequestId]);

  async function handleGenerate(requestId: string) {
    setBusyReqId(requestId);
    try {
      await onGenerateReport(requestId);
    } finally {
      setBusyReqId(null);
    }
  }

  return (
    <div className="grid grid-cols-1 gap-5 lg:grid-cols-12">
      {/* Left: Report Generation Queue & Generated Reports List */}
      <div className="space-y-4 lg:col-span-5">
        <div className="rounded-[28px] border border-white/80 bg-[#EDF2F3] p-5">
          <h2 className="text-lg font-semibold text-[#14191B]">
            Report Generation Eligibility
          </h2>
          <p className="mt-0.5 text-xs text-[#6B7A80]">
            Digital reports can only be generated after 100% of tests in a
            request are Verified.
          </p>

          <div className="mt-4 space-y-2.5">
            {requestReadiness.map(
              ({ req, verifiedCount, total, isReady, existingReport }) => (
                <div
                  key={req.id}
                  className="rounded-[20px] border border-white/90 bg-[#F8FAFA] p-3.5 text-xs"
                >
                  <div className="flex flex-wrap items-center justify-between gap-2">
                    <span className="font-semibold text-[#14191B]">
                      {req.id} — {req.patientName}
                    </span>
                    <span
                      className={`rounded-full px-2.5 py-0.5 text-[11px] font-semibold ${getLabBadgeClass(isReady ? "Verified" : "Pending")}`}
                    >
                      {verifiedCount}/{total} Verified
                    </span>
                  </div>
                  <p className="mt-1 text-[11px] text-[#6B7A80]">
                    Dr. {req.referringDoctor} • {req.priority}
                  </p>

                  <div className="mt-3 flex flex-wrap gap-2">
                    {existingReport ? (
                      <button
                        type="button"
                        onClick={() => setSelectedReportId(existingReport.id)}
                        className={ACCENT_BTN_CLASS}
                      >
                        View {existingReport.id}
                      </button>
                    ) : (
                      <button
                        type="button"
                        disabled={!canGenerate || !isReady || busyReqId === req.id}
                        onClick={() => handleGenerate(req.id)}
                        className={PRIMARY_BTN_CLASS}
                      >
                        {busyReqId === req.id
                          ? "Generating..."
                          : isReady
                            ? "Generate Digital Report"
                            : "Awaiting Verification"}
                      </button>
                    )}
                  </div>
                </div>
              )
            )}
          </div>
        </div>

        <div className="rounded-[28px] border border-white/80 bg-[#EDF2F3] p-5">
          <h3 className="text-base font-semibold text-[#14191B]">
            Issued Digital Reports ({reports.length})
          </h3>
          <div className="mt-3 space-y-2">
            {reports.map((rpt) => (
              <button
                key={rpt.id}
                type="button"
                onClick={() => setSelectedReportId(rpt.id)}
                className={`w-full rounded-[18px] border p-3 text-left text-xs transition ${
                  activeReport?.id === rpt.id
                    ? "border-[#181C1E] bg-[#181C1E] text-white"
                    : "border-white/90 bg-[#F8FAFA] text-[#14191B] hover:bg-white"
                }`}
              >
                <div className="flex items-center justify-between gap-2">
                  <span className="font-semibold">{rpt.id}</span>
                  <span
                    className={`text-[11px] ${
                      activeReport?.id === rpt.id
                        ? "text-[#B8C6CB]"
                        : "text-[#6B7A80]"
                    }`}
                  >
                    {formatDateTime(rpt.generatedAt)}
                  </span>
                </div>
                <p
                  className={`mt-0.5 text-[11px] ${
                    activeReport?.id === rpt.id
                      ? "text-[#DCE4E7]"
                      : "text-[#546369]"
                  }`}
                >
                  {rpt.patientName} • Request {rpt.requestId}
                </p>
              </button>
            ))}

            {reports.length === 0 && (
              <p className="rounded-[18px] bg-[#F8FAFA] py-6 text-center text-xs text-[#7D8C92]">
                No digital reports generated yet.
              </p>
            )}
          </div>
        </div>
      </div>

      {/* Right: Clinical Digital Report Preview + Print / Download PDF */}
      <div className="lg:col-span-7">
        {activeReport ? (
          <div className="rounded-[28px] border border-white/85 bg-white p-6 shadow-sm">
            <div className="flex flex-col gap-3 border-b border-[#E6EDEF] pb-4 sm:flex-row sm:items-start sm:justify-between">
              <div>
                <p className="text-[11px] font-semibold uppercase tracking-wider text-[#4A90A4]">
                  Healix Clinical Laboratory Report
                </p>
                <h3 className="mt-1 text-xl font-bold text-[#14191B]">
                  {activeReport.id}
                </h3>
                <p className="text-xs text-[#6B7A80]">
                  Generated {formatDateTime(activeReport.generatedAt)} •
                  Verified by {activeReport.verifiedBy}
                </p>
              </div>
              <button
                type="button"
                onClick={() => printLabReportPdf(activeReport)}
                className={PRIMARY_BTN_CLASS}
              >
                Print / Save PDF
              </button>
            </div>

            <div className="mt-4 grid grid-cols-1 gap-3 rounded-[20px] bg-[#F8FAFA] p-4 text-xs sm:grid-cols-2">
              <div>
                <p className="text-[10px] uppercase tracking-wider text-[#7D8C92]">
                  Patient
                </p>
                <p className="mt-0.5 font-semibold text-[#14191B]">
                  {activeReport.reportSnapshot.patient.fullName} (
                  {activeReport.reportSnapshot.patient.id})
                </p>
              </div>
              <div>
                <p className="text-[10px] uppercase tracking-wider text-[#7D8C92]">
                  Referring Physician
                </p>
                <p className="mt-0.5 font-semibold text-[#14191B]">
                  {activeReport.referringDoctor}
                </p>
              </div>
              <div>
                <p className="text-[10px] uppercase tracking-wider text-[#7D8C92]">
                  Request / Sample
                </p>
                <p className="mt-0.5 font-medium text-[#3B484D]">
                  {activeReport.reportSnapshot.requestId} •{" "}
                  {activeReport.reportSnapshot.sampleId} (
                  {activeReport.reportSnapshot.specimenType})
                </p>
              </div>
              <div>
                <p className="text-[10px] uppercase tracking-wider text-[#7D8C92]">
                  Priority
                </p>
                <p className="mt-0.5 font-medium text-[#3B484D]">
                  {activeReport.reportSnapshot.priority}
                </p>
              </div>
            </div>

            <div className="mt-5 overflow-x-auto">
              <table className="w-full text-left text-xs">
                <thead>
                  <tr className="border-b border-[#E6EDEF] text-[11px] uppercase tracking-wider text-[#6B7A80]">
                    <th className="py-2.5 pr-3">Test</th>
                    <th className="py-2.5 pr-3">Result</th>
                    <th className="py-2.5 pr-3">Reference Range</th>
                    <th className="py-2.5">Flag</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-[#EEF3F4]">
                  {activeReport.reportSnapshot.results.map((r) => (
                    <tr key={r.id}>
                      <td className="py-3 pr-3">
                        <p className="font-semibold text-[#14191B]">
                          {r.testName}
                        </p>
                        <p className="text-[11px] text-[#7D8C92]">
                          {r.testCode}
                        </p>
                      </td>
                      <td className="py-3 pr-3 font-bold text-[#14191B]">
                        {r.resultValue} {r.unit}
                      </td>
                      <td className="py-3 pr-3 text-[#546369]">
                        {r.referenceRange || "Qualitative"}
                      </td>
                      <td className="py-3">
                        <span
                          className={`rounded-full px-2.5 py-0.5 text-[11px] font-semibold ${getLabBadgeClass(
                            r.isOutOfRange ? "Out of Range" : "Normal"
                          )}`}
                        >
                          {r.isOutOfRange ? "Out of Range" : "Normal"}
                        </span>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>

            <div className="mt-5 flex flex-wrap items-center justify-between gap-2 border-t border-[#E6EDEF] pt-4 text-[11px] text-[#6B7A80]">
              <span>Verified By: {activeReport.verifiedBy}</span>
              <span>Issued By: {activeReport.generatedBy}</span>
            </div>
          </div>
        ) : (
          <div className="rounded-[28px] border border-white/80 bg-[#EDF2F3] p-10 text-center text-xs text-[#7D8C92]">
            Verify all test results for a request and generate its digital
            report to preview or download as PDF.
          </div>
        )}
      </div>
    </div>
  );
}
